def bullet(items: list[str], empty: str = "- TODO(agent): fill after inspection.") -> str:
    if not items:
        return empty
    return "\n".join(
        f"- `{sanitize_dynamic_text(item, 500) or '<empty>'}`" for item in items
    )


def command_table(commands: list[tuple[str, str, str]]) -> str:
    if not commands:
        return "| Command | Source | Status |\n|---|---|---|\n| TODO(agent): add verified commands | - | unknown |"
    rows = ["| Command | Source | Status |", "|---|---|---|"]
    for cmd, source, status in commands:
        safe_cmd = sanitize_dynamic_text(cmd, 500) or "<empty>"
        safe_source = sanitize_dynamic_text(source, 500) or "<empty>"
        safe_status = sanitize_dynamic_text(status, 100) or "unknown"
        rows.append(f"| `{safe_cmd}` | `{safe_source}` | {safe_status} |")
    return "\n".join(rows)


